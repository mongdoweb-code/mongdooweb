/** คืนชื่อจังหวัดมาตรฐาน หรือ null ถ้าไม่ใช่ 1 ใน 77 จังหวัด */
export function normalizeProvince(v: string): string | null {
  const s = v.trim().replace(/^จ(ังหวัด|\.)\s*/, "").trim();
  if (PROVINCE_ZIP[s]) return s;
  return ALIAS[s.toLowerCase()] ?? null;
}

/** รหัสไปรษณีย์ 5 หลัก ขึ้นต้นตรงกับจังหวัด */
export function zipMatchesProvince(zip: string, province: string) {
  const p = PROVINCE_ZIP[province];
  return /^\d{5}$/.test(zip) && !!p && p.includes(zip.slice(0, 2));
}

/** เบอร์มือถือ 10 หลัก (06/08/09) หรือเบอร์บ้าน/สำนักงาน 9 หลัก (02–05, 07) */
export function isThaiPhone(digits: string) {
  return /^0[689]\d{8}$/.test(digits) || /^0[2-57]\d{7}$/.test(digits);
}
